"""# Part 03-Create the SHAP explainer

Explanation: SHAP calculates how much each feature contributes to the model's prediction.I use TreeExplainer because Random Forest is a tree-based model.
"""

import joblib
import pandas as pd
import shap
import numpy as np

# 1. Load the Random Forest model and test dataset
random_forest = joblib.load('random_forest_model.joblib')
X_test = pd.read_csv('X_test.csv')

# 2. Initialize the TreeExplainer and calculate SHAP values
explainer = shap.TreeExplainer(random_forest)
shap_values = explainer.shap_values(X_test)

# Get SHAP values for class 1 (No-Show)
if isinstance(shap_values, list):
    shap_values_class1 = shap_values[1]
elif isinstance(shap_values, np.ndarray) and shap_values.ndim == 3:
    shap_values_class1 = shap_values[:, :, 1]
else:
    shap_values_class1 = shap_values

print("SHAP values calculated successfully!")
print("Shape:", shap_values_class1.shape)

"""# Part 04-Global explanation (SHAP Summary Plot)

Explanation: This plot shows which features are important for predicting appointment no-shows across all test patients.
- Each dot represents a patient.
- Red indicates a high feature value.
- Blue indicates a low feature value.
- The horizontal position shows how the feature pushes the prediction.
"""

shap.summary_plot(
    shap_values_class1,
    X_test,
    max_display=15
)

"""#Part 05-SHAP Feature Importance Bar Plot

Explanation: This chart ranks features based on their average importance across the test data. The higher the bar, the more influence that feature has on the model overall.
"""

shap.summary_plot(
    shap_values_class1,
    X_test,
    plot_type="bar",
    max_display=15
)

"""#Part 06-Local explanation (High-risk No-Show patient)

Explanation:I find one patient whom the model predicted as likely to miss the appointment and examine the factors that influenced that prediction.
"""

import pandas as pd
import numpy as np

# Load y_test since it hasn't been defined in the session yet
y_test = pd.read_csv('y_test.csv')

y_pred = random_forest.predict(X_test)
y_proba = random_forest.predict_proba(X_test)[:, 1]

# Find a correctly predicted No-Show patient
high_risk_idx = np.where((y_pred == 1) & (y_test.values.ravel() == 1))[0][0]

print("Patient index:", high_risk_idx)
print("Predicted No-Show probability:", round(y_proba[high_risk_idx], 2))

"""SHAP Waterfall Plot
Explanation: The waterfall plot shows how different features increase or decrease the No-Show prediction for this particular patient.
- Red features → increase predicted No-Show risk.
- Blue features → decrease predicted No-Show risk.
"""

expected_value = explainer.expected_value

if isinstance(expected_value, (list, np.ndarray)) and np.ndim(expected_value) > 0:
    expected_value_class1 = expected_value[1]
else:
    expected_value_class1 = expected_value

patient_explanation = shap.Explanation(
    values=shap_values_class1[high_risk_idx],
    base_values=expected_value_class1,
    data=X_test.iloc[high_risk_idx].values,
    feature_names=X_test.columns.tolist()
)

shap.plots.waterfall(patient_explanation, max_display=10)

"""# Part 07-Local explanation (Low-risk patient)

Explanation:I examine a patient predicted to attend the appointment (lower No-Show risk) and identify the features influencing that prediction.
"""

# Find a correctly predicted Attended/Other patient
low_risk_idx = np.where((y_pred == 0) & (y_test.values == 0))[0][0]

print("Patient index:", low_risk_idx)
print("Predicted No-Show probability:", round(y_proba[low_risk_idx], 2))

patient_explanation_low = shap.Explanation(
    values=shap_values_class1[low_risk_idx],
    base_values=expected_value_class1,
    data=X_test.iloc[low_risk_idx].values,
    feature_names=X_test.columns.tolist()
)

shap.plots.waterfall(patient_explanation_low, max_display=10)

"""This helps me compare the features that push a prediction toward No-Show versus the features that push it away.

# Part 08-Feature Dependence Plot

Explanation: A dependence plot helps me to understand how one feature affects the No-Show prediction.

I select the most important feature automatically from the SHAP importance results.
"""

mean_abs_shap = pd.DataFrame({
    "Feature": X_test.columns,
    "Mean_Absolute_SHAP": np.abs(shap_values_class1).mean(axis=0)
}).sort_values("Mean_Absolute_SHAP", ascending=False)

top_feature = mean_abs_shap.iloc[0]["Feature"]

print("Most important feature:", top_feature)

shap.dependence_plot(
    top_feature,
    shap_values_class1,
    X_test
)

"""# Part 09-Save the SHAP Feature Importance Table

Explanation:I save a CSV table that ranks the features according to their average SHAP importance. This can be included in the project report.
"""

mean_abs_shap = pd.DataFrame({
    "Feature": X_test.columns,
    "Mean_Absolute_SHAP": np.abs(shap_values_class1).mean(axis=0)
}).sort_values("Mean_Absolute_SHAP", ascending=False)

mean_abs_shap.to_csv("task07_shap_feature_importance.csv", index=False)

