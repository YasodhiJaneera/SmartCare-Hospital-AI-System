"""# Part 03-Evaluate all models"""

# Load the uploaded datasets
import os
import zipfile
import pandas as pd
import joblib
import numpy as np
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score

# 1. Load data
X_test = pd.read_csv('X_test.csv')
y_test = pd.read_csv('y_test.csv')

# Ensure 1D shape for y_test if it is loaded as a DataFrame
if isinstance(y_test, pd.DataFrame):
    y_test = y_test.iloc[:, 0]

# 2. Extract and load models from the uploaded zip file
zip_path = 'Task05_ML_Results.zip'
extract_path = '/content/extracted_models'
os.makedirs(extract_path, exist_ok=True)

with zipfile.ZipFile(zip_path, 'r') as zip_ref:
    zip_ref.extractall(extract_path)

# Define output folders used in subsequent cells
evaluation_folder = '/content/evaluation_reports'
tables_folder = '/content/tables'
models_folder = '/content/models'
os.makedirs(evaluation_folder, exist_ok=True)
os.makedirs(tables_folder, exist_ok=True)
os.makedirs(models_folder, exist_ok=True)

# Find and load the .joblib model files into best_models
best_models = {}
for root, dirs, files in os.walk(extract_path):
    for file in files:
        if file.endswith('.joblib') and file != 'best_model.joblib':
            model_name = os.path.splitext(file)[0].replace('_', ' ').title()
            model_path = os.path.join(root, file)
            best_models[model_name] = joblib.load(model_path)

print(f"Loaded models: {list(best_models.keys())}")

# 3. Calculate Accuracy, Precision, Recall, F1-score, and ROC-AUC
results = []

for model_name, model in best_models.items():
    y_pred = model.predict(X_test)

    # Basic metrics
    accuracy = accuracy_score(y_test, y_pred)
    precision = precision_score(y_test, y_pred, zero_division=0)
    recall = recall_score(y_test, y_pred, zero_division=0)
    f1 = f1_score(y_test, y_pred, zero_division=0)

    # ROC-AUC
    if hasattr(model, 'predict_proba'):
        y_score = model.predict_proba(X_test)[:, 1]
        roc_auc = roc_auc_score(y_test, y_score)
    elif hasattr(model, 'decision_function'):
        y_score = model.decision_function(X_test)
        roc_auc = roc_auc_score(y_test, y_score)
    else:
        roc_auc = np.nan

    results.append({
        'Model': model_name,
        'Accuracy': accuracy,
        'Precision': precision,
        'Recall': recall,
        'F1 Score': f1,
        'ROC-AUC': roc_auc
    })

evaluation_df = pd.DataFrame(results)
display(evaluation_df.round(4))

"""# Part 04-Generate confusion matrices"""

#Create a confusion matrix for each model.

for model_name, model in best_models.items():

    y_pred = model.predict(X_test)

    cm = confusion_matrix(y_test, y_pred)

    plt.figure(figsize=(5, 4))

    sns.heatmap(
        cm,
        annot=True,
        fmt='d',
        cmap='Blues'
    )

    plt.title(f'Confusion Matrix - {model_name}')
    plt.xlabel('Predicted')
    plt.ylabel('Actual')

    filename = model_name.lower().replace(' ', '_') + '_confusion_matrix.png'

    plt.savefig(
        os.path.join(evaluation_folder, filename),
        dpi=300,
        bbox_inches='tight'
    )

    plt.show()
    plt.close()

print("Confusion matrices saved!")

