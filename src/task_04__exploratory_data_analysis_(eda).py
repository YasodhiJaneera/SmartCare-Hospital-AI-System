"""##  Generate an outlier summary using IQR"""

outlier_results = []

for col in ['age', 'waiting_days',
            'previous_appointments',
            'missed_previous_appointments']:

    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)

    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    count = ((df[col] < lower) | (df[col] > upper)).sum()

    outlier_results.append({
        'Feature': col,
        'Lower Bound': lower,
        'Upper Bound': upper,
        'Outlier Count': count
    })

outlier_df = pd.DataFrame(outlier_results)

display(outlier_df)

