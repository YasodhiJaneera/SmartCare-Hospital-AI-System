import os
import pandas as pd

# Create the tables folder
tables_folder = '/content/smartcare-hospital-ai/reports/tables'
os.makedirs(tables_folder, exist_ok=True)

# 1. Descriptive statistics
df.describe(include='all').transpose().to_csv(
    f'{tables_folder}/descriptive_statistics.csv'
)

# 2. Correlation matrix (numerical columns)
df.select_dtypes(include='number').corr().to_csv(
    f'{tables_folder}/correlation_matrix.csv'
)

# 3. Outlier analysis using IQR
numeric_df = df.select_dtypes(include='number')

outlier_results = []

for column in numeric_df.columns:
    Q1 = numeric_df[column].quantile(0.25)
    Q3 = numeric_df[column].quantile(0.75)
    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    outlier_count = (
        (numeric_df[column] < lower_bound) |
        (numeric_df[column] > upper_bound)
    ).sum()

    outlier_results.append({
        'Feature': column,
        'Q1': Q1,
        'Q3': Q3,
        'IQR': IQR,
        'Lower_Bound': lower_bound,
        'Upper_Bound': upper_bound,
        'Outlier_Count': outlier_count
    })

pd.DataFrame(outlier_results).to_csv(
    f'{tables_folder}/outlier_analysis.csv',
    index=False
)

# 4. Target distribution
df['no_show'].value_counts().sort_index().rename_axis(
    'no_show'
).reset_index(name='count').to_csv(
    f'{tables_folder}/target_distribution.csv',
    index=False
)

